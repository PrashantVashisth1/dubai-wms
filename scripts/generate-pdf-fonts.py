"""
Regenerates src/lib/server/pdf/fontData.ts (dev-time only; needs Python + fontTools).

  python scripts/generate-pdf-fonts.py [path/to/arial.ttf] [path/to/arialbd.ttf]

- Carlito (SIL OFL 1.1, metric-compatible with Calibri) is embedded in PDFs.
  The TTFs in src/lib/server/pdf/fonts/ are already subset to WinAnsi (cp1252):
    pyftsubset Carlito-Regular.ttf --unicodes=U+0020-007E,U+00A0-00FF,<cp1252 extras>
      --layout-features='' --no-hinting --drop-tables+=GSUB,GPOS,GDEF,DSIG,kern
- Helvetica is a PDF base-14 font (not embedded). Only its advance widths are
  generated here, read from Arial, which shares Helvetica's metrics.
"""
import base64
import os
import sys

from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, 'src', 'lib', 'server', 'pdf', 'fonts')
OUT = os.path.join(ROOT, 'src', 'lib', 'server', 'pdf', 'fontData.ts')


def win_ansi_unicode(code):
    try:
        return ord(bytes([code]).decode('cp1252'))
    except UnicodeDecodeError:
        return None


def metrics(path):
    font = TTFont(path)
    upem = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    scale = 1000 / upem
    widths = []
    for code in range(32, 256):
        uni = win_ansi_unicode(code)
        glyph = cmap.get(uni) if uni is not None else None
        widths.append(round(hmtx[glyph][0] * scale) if glyph else 0)
    os2 = font['OS/2']
    head = font['head']
    return {
        'widths': widths,
        'ascent': round(font['hhea'].ascent * scale),
        'descent': round(font['hhea'].descent * scale),
        'capHeight': round(getattr(os2, 'sCapHeight', 0) * scale) or round(font['hhea'].ascent * scale * 0.7),
        'bbox': [round(head.xMin * scale), round(head.yMin * scale), round(head.xMax * scale), round(head.yMax * scale)],
        'postScriptName': font['name'].getDebugName(6),
    }


def main():
    arial = sys.argv[1] if len(sys.argv) > 1 else 'C:/Windows/Fonts/arial.ttf'
    arial_bold = sys.argv[2] if len(sys.argv) > 2 else 'C:/Windows/Fonts/arialbd.ttf'
    helv = metrics(arial)['widths']
    helv_bold = metrics(arial_bold)['widths']
    parts = [
        '// GENERATED by scripts/generate-pdf-fonts.py - do not edit by hand.',
        '// Carlito fonts: SIL Open Font License 1.1 (see ./fonts/OFL-Carlito.txt).',
        '// Widths are 1/1000 em for WinAnsi codes 32..255.',
        '',
        'export type FontMetrics = { widths: number[]; ascent: number; descent: number; capHeight: number; bbox: number[]; postScriptName: string };',
        'export type EmbeddedFontData = FontMetrics & { base64: string };',
        '',
        f'export const HELVETICA_WIDTHS: number[] = {helv};',
        f'export const HELVETICA_BOLD_WIDTHS: number[] = {helv_bold};',
        '',
    ]
    for key, file in [('CARLITO_REGULAR', 'Carlito-Regular.ttf'), ('CARLITO_BOLD', 'Carlito-Bold.ttf')]:
        path = os.path.join(FONT_DIR, file)
        m = metrics(path)
        data = base64.b64encode(open(path, 'rb').read()).decode('ascii')
        parts.append(
            f"export const {key}: EmbeddedFontData = {{ postScriptName: '{m['postScriptName']}', widths: {m['widths']}, "
            f"ascent: {m['ascent']}, descent: {m['descent']}, capHeight: {m['capHeight']}, bbox: {m['bbox']}, base64: '{data}' }};"
        )
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(parts) + '\n')
    print('wrote', OUT, os.path.getsize(OUT), 'bytes')


if __name__ == '__main__':
    main()
